#!/bin/sh
#j857
# SH0 (PLAN/022): build and install the pinned prebuilt sysroot for
# aarch64-unknown-kumo from the same staged std build the image uses, and stamp it.
#
#     scripts/rust-sysroot.sh [--check-repro]
#
# Output (build/sysroot/aarch64-unknown-kumo by default, KUMO_SYSROOT_OUT overrides):
#     lib/rustlib/aarch64-unknown-kumo/lib/*.rlib|*.rmeta   build-std artifacts
#     lib/rustlib/aarch64-unknown-kumo.json                 the tracked target spec
#     share/kumo/{start.o,link.ld,libkumo_shim.a,libc.a}    the link contract
#     manifest.json                                         input + artifact pin
#     cargo-config.toml                                     consumer fragment
#
# --check-repro additionally rebuilds std in a fresh target dir and compares every
# installed artifact hash; the comparison is recorded, never inferred.
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TOOLCHAIN="nightly-2026-06-22"
TARGET_JSON="$ROOT/targets/aarch64-unknown-kumo.json"
OUT="${KUMO_SYSROOT_OUT:-$ROOT/build/sysroot/aarch64-unknown-kumo}"
STAGE="${KUMO_RUST_STD_STAGE_OUT:-$ROOT/target/rust-std-stage}"
STD_TARGET_DIR="${KUMO_RUST_STD_TARGET_DIR:-$ROOT/target/rust-std-smoke}"
LIBC_SYSROOT="${KUMO_SYSROOT:-$ROOT/target/kumo-sysroot}"
REPRO=0
[ "${1:-}" = "--check-repro" ] && REPRO=1

fail() { printf 'rust-sysroot: %s\n' "$1" >&2; exit 1; }

command -v cargo >/dev/null 2>&1 || fail "cargo is required"
command -v shasum >/dev/null 2>&1 || fail "shasum is required"
[ -f "$TARGET_JSON" ] || fail "missing $TARGET_JSON"

# The C side of the link must exist before the std build; build it when absent.
if [ ! -f "$LIBC_SYSROOT/lib/libc.a" ]; then
    sh "$ROOT/scripts/relibc-headers.sh" || fail "relibc-headers failed"
fi

# Build the std artifacts through the one staged build path the image uses.
KUMO_RUST_STD_TARGET_DIR="$STD_TARGET_DIR" sh "$ROOT/scripts/rust-std-check.sh" \
    || fail "rust-std-check failed"
deps="$STD_TARGET_DIR/aarch64-unknown-kumo/release/deps"
[ -d "$deps" ] || fail "no std artifacts under $deps"
[ -f "$STAGE/start.o" ] || fail "missing $STAGE/start.o"
[ -f "$STAGE/stublibs/libkumo_shim.a" ] || fail "missing the kumo shim archive"

# A clean install every time; the manifest is the record, not the cache.
rm -rf "$OUT"
mkdir -p "$OUT/lib/rustlib/aarch64-unknown-kumo/lib" "$OUT/share/kumo"
cp "$deps"/*.rlib "$deps"/*.rmeta "$OUT/lib/rustlib/aarch64-unknown-kumo/lib/"
cp "$TARGET_JSON" "$OUT/lib/rustlib/aarch64-unknown-kumo.json"
cp "$TARGET_JSON" "$OUT/share/kumo/aarch64-unknown-kumo.json"
cp "$STAGE/start.o" "$OUT/share/kumo/start.o"
cp "$ROOT/toolchain/rust/smoke/link.ld" "$OUT/share/kumo/link.ld"
cp "$STAGE/stublibs/libkumo_shim.a" "$OUT/share/kumo/libkumo_shim.a"
# std's unix link line asks for -lunwind; the stub archive (empty under panic_abort)
# lives beside the shim and must ship in the link contract with it.
cp "$STAGE/stublibs/libunwind.a" "$OUT/share/kumo/libunwind.a"
cp "$LIBC_SYSROOT/lib/libc.a" "$OUT/share/kumo/libc.a"

# The consumer fragment. Cargo has no sysroot key; --sysroot rides RUSTFLAGS, and the
# link contract is the same one the std smoke proves.
cat > "$OUT/cargo-config.toml" <<EOF
# Generated by scripts/rust-sysroot.sh (PLAN/022 SH0). Paths name this install.
[target.aarch64-unknown-kumo]
rustflags = [
    "--sysroot=$OUT",
    "-Clink-arg=-T$OUT/share/kumo/link.ld",
    "-Clink-arg=$OUT/share/kumo/start.o",
    "-Clink-arg=$OUT/share/kumo/libkumo_shim.a",
    "-Clink-arg=$OUT/share/kumo/libc.a",
    "-Clink-arg=-L$OUT/share/kumo",
    "-Clink-arg=-z",
    "-Clink-arg=muldefs",
]
EOF

write_manifest() {
    python3 - "$1" "$ROOT" "$TOOLCHAIN" "$TARGET_JSON" "$LIBC_SYSROOT" <<'PY'
import hashlib, json, pathlib, subprocess, sys

out, root, toolchain, target_json, libc_sysroot = sys.argv[1:6]
out = pathlib.Path(out)
root = pathlib.Path(root)

def sha(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()

version = subprocess.check_output(
    ["rustc", "+" + toolchain, "--version", "--verbose"], text=True)
inputs = {}
for rel in (
    "scripts/rust-sysroot.sh",
    "scripts/rust-std-check.sh",
    "scripts/relibc-headers.sh",
    "targets/aarch64-unknown-kumo.json",
    "toolchain/relibc/SOURCE.lock",
    "toolchain/relibc/kumo.patch",
    "toolchain/rust/smoke/start.S",
    "toolchain/rust/smoke/link.ld",
    "toolchain/rust/shim/shim.c",
):
    inputs[rel] = sha(root / rel)
inputs["libc.a"] = sha(pathlib.Path(libc_sysroot) / "lib/libc.a")

artifacts = {}
for path in sorted(out.rglob("*")):
    if path.is_file() and path.name not in ("manifest.json", "cargo-config.toml"):
        artifacts[str(path.relative_to(out))] = sha(path)

manifest = {
    "schema": 1,
    "target": "aarch64-unknown-kumo",
    "toolchain": toolchain,
    "rustc": version.strip().splitlines()[0],
    "inputs": inputs,
    "artifacts": artifacts,
}
(out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
print(f"rust-sysroot: manifest {out / 'manifest.json'} ({len(artifacts)} artifacts)")
PY
}

write_manifest "$OUT"

if [ "$REPRO" -eq 1 ]; then
    ALT="$OUT-repro"
    KUMO_SYSROOT_OUT="$ALT" \
    KUMO_RUST_STD_TARGET_DIR="$ROOT/target/rust-std-repro" \
        sh "$ROOT/scripts/rust-sysroot.sh" || fail "clean rebuild failed"
    python3 - "$OUT/manifest.json" "$ALT/manifest.json" <<'PY'
import json, sys
a = json.load(open(sys.argv[1]))
b = json.load(open(sys.argv[2]))
if a["artifacts"] != b["artifacts"]:
    diff = sorted(set(a["artifacts"]) ^ set(b["artifacts"])) or [
        k for k in a["artifacts"] if a["artifacts"][k] != b["artifacts"].get(k)]
    print("rust-sysroot: REPRO FAIL", diff[:8], file=sys.stderr)
    sys.exit(1)
print(f"rust-sysroot: REPRO OK ({len(a['artifacts'])} artifacts identical across a clean rebuild)")
PY
fi
