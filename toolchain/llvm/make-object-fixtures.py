"""Make deterministic host inputs for the native ELF/archive reader proof."""
import hashlib
from pathlib import Path
import struct
import subprocess


def generate(out, generated):
    out.mkdir(parents=True, exist_ok=True)
    source = Path(__file__).with_name("object-fixture.S")
    members = (("aarch64-unknown-none", "aarch64.o", "FixtureELF64LE"),
               ("armeb-none-eabi", "arm32-big-endian-long-member-name.o", "FixtureELF32BE"))
    for triple, name, _ in members:
        subprocess.run(["clang", "--target=" + triple, "-c", str(source), "-o", str(out / name)], check=True)
    archive = out / "objects.a"
    archive.unlink(missing_ok=True)
    subprocess.run(["llvm-ar", "--format=gnu", "rcsD", str(archive),
                    *(str(out / name) for _, name, _ in members)], check=True)

    # A bad name offset must surface as an Error rather than an out-of-range read. — KESTREL
    data = bytearray((out / "aarch64.o").read_bytes())
    shoff, = struct.unpack_from("<Q", data, 0x28)
    shsize, shnum = struct.unpack_from("<HH", data, 0x3a)
    sections = [struct.unpack_from("<IIQQQQIIQQ", data, shoff + i * shsize) for i in range(shnum)]
    changed = False
    for section in sections:
        if section[1] != 2:  # SHT_SYMTAB
            continue
        strings = sections[section[6]]
        for offset in range(section[4], section[4] + section[5], section[9]):
            name_offset, = struct.unpack_from("<I", data, offset)
            start = strings[4] + name_offset
            if data[start:data.index(0, start)] == b"sh9_answer":
                struct.pack_into("<I", data, offset, 0xffffffff)
                changed = True
    if not changed:
        raise RuntimeError("fixture lacks the sh9_answer symbol")
    (out / "bad-symbol.o").write_bytes(data)

    arrays = [(name, symbol) for _, name, symbol in members]
    arrays += [("objects.a", "FixtureArchive"), ("bad-symbol.o", "FixtureBadSymbol")]
    header = ["// Generated by make-object-fixtures.py; host-produced parser inputs.\n"]
    for name, symbol in arrays:
        data = (out / name).read_bytes()
        header.append(f"alignas(8) static const unsigned char {symbol}[] = {{\n")
        header.extend("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",\n"
                      for i in range(0, len(data), 16))
        header.append("};\n")
    (generated / "object-fixtures.h").write_text("".join(header))
    return {
        "scope": "host-produced ELF64LE AArch64 and ELF32BE ARM objects plus a regular GNU archive",
        "clang": subprocess.check_output(["clang", "--version"], text=True).strip(),
        "llvm_ar": subprocess.check_output(["llvm-ar", "--version"], text=True).strip(),
        "files_sha256": {name: hashlib.sha256((out / name).read_bytes()).hexdigest() for name, _ in arrays},
    }
