"""Assemble a pinned-version host bitcode fixture for native reading (SH9-d7)."""
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess

TOOL = Path(__file__).resolve().parent


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def generate(out, generated):
    lock = json.loads((TOOL / "SOURCE.lock").read_text())
    version = lock["ref"].removeprefix("llvmorg-")
    candidates = (os.environ.get("LLVM_AS"), f"/opt/homebrew/opt/llvm@{version.split('.')[0]}/bin/llvm-as",
                  shutil.which("llvm-as-" + version.split('.')[0]), shutil.which("llvm-as"))
    candidate = next((p for p in candidates if p and Path(p).is_file()), None)
    if not candidate:
        raise RuntimeError(f"LLVM {version} llvm-as is required; set LLVM_AS")
    assembler = Path(candidate).resolve()
    banner = subprocess.check_output([str(assembler), "--version"], text=True).strip()
    if not re.search(r"\bLLVM version " + re.escape(version) + r"\b", banner):
        raise RuntimeError(f"fixture assembler must match LLVM {version}: {banner}")
    out.mkdir(parents=True, exist_ok=True)
    generated.mkdir(parents=True, exist_ok=True)
    source = TOOL / "ir-fixture.ll"
    bitcode = out / "input.bc"
    subprocess.run([str(assembler), str(source), "-o", str(bitcode)], check=True)
    header = generated / "ir-fixtures.h"
    text = "// Generated by make-ir-fixtures.py; host-assembled input, not native bitcode emission.\n#pragma once\n"
    for name, data in (("FixtureIR", source.read_bytes() + b"\0"), ("FixtureBitcode", bitcode.read_bytes())):
        text += f"inline constexpr unsigned char {name}[] = {{\n"
        text += "\n".join("    " + ", ".join(f"0x{b:02x}" for b in data[i:i+16]) + "," for i in range(0, len(data), 16))
        text += "\n};\n"
    header.write_text(text)
    shutil.copyfile(source, out / "input.ll")
    result = {"producer": str(assembler), "version": banner, "tool_sha256": sha(assembler),
              "source_sha256": sha(source), "bitcode_sha256": sha(bitcode), "bitcode_bytes": bitcode.stat().st_size,
              "header_sha256": sha(header), "scope": "host assembles; native proof reads and disassembles"}
    (out / "manifest.json").write_text(json.dumps(result, indent=2) + "\n")
    return result
