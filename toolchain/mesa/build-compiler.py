def run(command, cwd=None, env=None):
    result = subprocess.run(list(map(str, command)), cwd=cwd, env=env, capture_output=True, text=True)
    if result.returncode:
        raise RuntimeError(" ".join(map(str, command)) + "\n" + result.stdout + result.stderr)
    return result.stdout


def tool_env():
    import os
    env = dict(os.environ)
    env["PATH"] = TOOL_PATH + ":" + env["PATH"]
    env["CC"], env["CXX"] = "clang-22", "clang++-22"
    return env


def reference():
    """R0: scripts/build-mali-shaders.sh's two commands, verbatim, in a scratch directory."""
    work = OUT / "reference"
    shutil.rmtree(work, ignore_errors=True)
    work.mkdir(parents=True)
    shutil.copyfile(ROOT / "shaders/mali/kumo_paint.cl", work / "kumo_paint.cl")
    m = SHADER_SOURCE
    run([SHADER_BUILD / "src/compiler/clc/mesa_clc", "-o", "kumo_paint_v10.spv", "--depfile",
         "kumo_paint_v10.d", "kumo_paint.cl", "--", "-DPAN_ARCH=10", f"-I{m}/include",
         f"-I{m}/src/compiler/libcl", f"-I{m}/src", f"-I{m}/src/panfrost", "-cl-std=cl2.0",
         "-D__OPENCL_VERSION__=200"], cwd=work)
    run([SHADER_BUILD / "src/panfrost/clc/panfrost_compile", "kumo_shaders", "10", "kumo_paint_v10.spv",
         "kumo_paint_v10.h", "kumo_paint_v10.c"], cwd=work)
    return work


def inputs_header(spirv):
    def array(name, data):
        body = ",".join(str(b) for b in data)
        return f"static const unsigned char {name}[{len(data)}] = {{{body}}};\n"
    text = "/* Generated by toolchain/mesa/build-compiler.py (G7n). */\n"
    text += array("g7n_kumo_paint_spv", spirv)
    for name in ("paint", "math"):
        source = (TOOL / f"g7n/{name}.comp").read_bytes() + b"\0"
        text += array(f"g7n_{name}_comp_bytes", source)
        text += f"#define g7n_{name}_comp ((const char *)g7n_{name}_comp_bytes)\n"
    gen = OUT / "gen"
    gen.mkdir(exist_ok=True)
    (gen / "g7n-inputs.h").write_text(text)
    return gen


def configure_linux():
    if not (LINUX / "build.ninja").exists():
        run(["meson", "setup", LINUX, SOURCE, "--wrap-mode=nodownload", *LINUX_OPTIONS], env=tool_env())


def flags(build, extra_entries, base_entry="gallium/drivers/panfrost/pan_shader.c"):
    """The flags of `base_entry` (C: gallium's pan_shader.c), plus the other entries' includes."""
    commands = json.loads((build / "compile_commands.json").read_text())

    def entry(suffix):
        return next(c for c in commands if c["file"].endswith(suffix))

    def split(e):
        out, skip = [], False
        for arg in shlex.split(e["command"])[1:]:
            if skip:
                skip = False
            elif arg in ("-o", "-MF", "-MQ", "-MT"):
                skip = True
            elif arg not in ("-c", "-MD", "-MMD", e["file"]) and not arg.startswith("-W"):
                out.append(arg)
        return out

    base = split(entry(base_entry))
    for suffix in extra_entries:
        for arg in split(entry(suffix)):
            if arg.startswith("-I") and arg not in base:
                base.append(arg)
    return base


def build_platform(build, name, gen, compile_cc, objects_out):
    run(["ninja", "-C", build, "-j8", *ARCHIVES], env=tool_env())
    cflags = flags(build, ["src/compiler/glsl/gl_nir_linker.c", "src/compiler/spirv/spirv_to_nir.c",
                           "src/panfrost/compiler/pan_compiler.c"])
    cflags += ["-I", str(SOURCE / "src"), "-I", str(SOURCE / "src/mesa"), "-I", str(build / "src"),
               "-I", str(build / "src/mesa"), "-I", str(build / "src/compiler/nir"),
               "-I", str(SOURCE / "src/compiler/nir"), "-I", str(gen)]
    objdir = OUT / name
    objdir.mkdir(exist_ok=True)
    harness = objdir / "compiler-smoke.o"
    run([compile_cc, *cflags, "-Wall", "-Wextra", "-Werror", "-Wno-unused-parameter",
         "-Wno-missing-field-initializers", "-Wno-sign-compare", "-c", TOOL / "compiler-smoke.c",
         "-o", harness], cwd=build)
    upstream = objdir / "pan_compile.o"
    # Upstream source, compiled unchanged; its entry point and file calls are renamed in the object
    # (compiler-smoke.c supplies the g7n_* layer). Symbols, not macros: glibc redirects open,
    # lseek, mmap and fopen to their *64 names in its headers, so both spellings are renamed.
    run([compile_cc, *cflags, "-w", "-c", SOURCE / "src/panfrost/clc/pan_compile.c", "-o",
         upstream], cwd=build)
    renames = {"main": "pan_compile_main", "open": "g7n_open", "lseek": "g7n_lseek",
               "close": "g7n_close", "mmap": "g7n_file_mmap", "munmap": "g7n_file_munmap",
               "fopen": "g7n_fopen"}
    redefine = []
    for old, new in renames.items():
        redefine += ["--redefine-sym", f"{old}={new}"]
        if old != "main" and old != "close":
            redefine += ["--redefine-sym", f"{old}64={new}"]
    run(["llvm-objcopy-22", *redefine, upstream])
    imports = run(["llvm-nm-22", "--undefined-only", upstream])
    for old in renames:
        for name in (old, old + "64"):
            assert f" U {name}\n" not in imports, f"pan_compile.o still imports {name}"
    cxxflags = flags(build, ["src/compiler/glsl/gl_nir_linker.c"],
                     base_entry="src/compiler/glsl/standalone_scaffolding.cpp")
    shim = objdir / "compiler-smoke-glsl.o"
    run(["clang++-22", *cxxflags, "-Wall", "-Wextra", "-Werror", "-Wno-unused-parameter", "-c",
         TOOL / "compiler-smoke-glsl.cpp", "-o", shim], cwd=build)
    objects_out.extend([harness, upstream, shim])
    return cflags


STACK_BYTES = 2 * 1024 * 1024


def link_script():
    """The relibc smoke script plus a PT_GNU_STACK header that `-z stack-size` fills: Sora's loader
    gives thread zero that stack (J741). Mesa's GLSL front end outran the 16 KiB default."""
    script = (ROOT / "toolchain/relibc/smoke/link.ld").read_text()
    assert script.count("    tls    PT_TLS  FLAGS(4);") == 1
    script = script.replace("    tls    PT_TLS  FLAGS(4);",
                            "    tls    PT_TLS  FLAGS(4);\n    stack  PT_GNU_STACK FLAGS(6);")
    path = OUT / "kumo" / "link.ld"
    path.write_text(script)
    return path


def set_stack_size(elf, size):
    """Write `size` into the image's one PT_GNU_STACK p_memsz. With an explicit PHDRS block lld
    emits the header but leaves it zero (`-z stack-size` fills only the header lld creates
    itself), so the build writes the same field that option would."""
    import struct
    data = bytearray(elf.read_bytes())
    assert data[:4] == b"\x7fELF" and data[4] == 2 and data[5] == 1, "ELF64 little-endian expected"
    phoff, = struct.unpack_from("<Q", data, 0x20)
    phentsize, phnum = struct.unpack_from("<HH", data, 0x36)
    hits = [phoff + i * phentsize for i in range(phnum)
            if struct.unpack_from("<I", data, phoff + i * phentsize)[0] == 0x6474E551]
    assert len(hits) == 1, "exactly one PT_GNU_STACK"
    struct.pack_into("<Q", data, hits[0] + 40, size)
    elf.write_bytes(bytes(data))


def link_kumo(objects):
    runtime = Path("/output/cxx/libkumo-cxx.a")
    libc = MESA / "sysroot/lib/libc.a"
    crt0 = OUT / "kumo" / "crt0.o"
    run(["clang-22", "--target=aarch64-unknown-none", "-c", ROOT / "toolchain/relibc/smoke/crt0.S",
         "-o", crt0])
    elf = OUT / "compiler-smoke"
    archives = [KUMO / a for a in ARCHIVES]
    drm = OUT / "kumo" / "drm-refusal.o"
    script = link_script()
    lld = ["ld.lld-22", "-static", "--gc-sections", "-z", "noexecstack", "-T", script,
           f"-Map={elf}.map", "-o", elf]
    run([*lld, crt0, *objects, "--start-group", runtime, *archives, libc, "--end-group"])
    undefined = run(["llvm-nm-22", "--undefined-only", elf])
    if undefined.strip():
        # A retained DRM reference resolves to the measured refusals (G7m), never to success.
        flags_drm = flags(KUMO, [])
        run(["clang-22", *flags_drm, "-I", str(MESA / "drm"), "-c", TOOL / "drm-refusal.c", "-o", drm],
            cwd=KUMO)
        run([*lld, crt0, *objects, drm, "--start-group", runtime, *archives, libc, "--end-group"])
        undefined = run(["llvm-nm-22", "--undefined-only", elf])
    assert not undefined.strip(), "KUMO compiler smoke has undefined symbols:\n" + undefined
    set_stack_size(elf, STACK_BYTES)
    headers = run(["llvm-readelf-22", "-lW", elf])
    stack = [line.split() for line in headers.splitlines() if line.strip().startswith("GNU_STACK")]
    assert len(stack) == 1 and int(stack[0][5], 16) == STACK_BYTES, headers
    return elf


def link_linux(objects):
    elf = OUT / "compiler-smoke-linux"
    run(["clang++-22", "-o", elf, *objects, "-Wl,--start-group", *[LINUX / a for a in ARCHIVES],
         "-Wl,--end-group", "-lm", "-lpthread"])
    return elf


def main():
    OUT.mkdir(exist_ok=True)
    ref = reference()
    spirv = (ref / "kumo_paint_v10.spv").read_bytes()
    gen = inputs_header(spirv)

    kumo_objects, linux_objects = [], []
    kumo_flags = build_platform(KUMO, "kumo", gen, "clang-22", kumo_objects)
    configure_linux()
    linux_flags = build_platform(LINUX, "linux", gen, "clang-22", linux_objects)
    kumo_elf = link_kumo(kumo_objects)
    linux_elf = link_linux(linux_objects)

    scratch = OUT / "linux-run"
    shutil.rmtree(scratch, ignore_errors=True)
    scratch.mkdir()
    transcript = run([linux_elf, scratch])
    (OUT / "linux.txt").write_text(transcript)
    assert GREEN in transcript and "FAILED" not in transcript, transcript
    for name in ("kumo_paint_v10.h", "kumo_paint_v10.c"):
        assert (scratch / name).read_bytes() == (ref / name).read_bytes(), \
            f"R1 {name} differs from the shader recipe's panfrost_compile (R0)"
    print("G7n Linux reference green: R1 reproduces R0's panfrost_compile outputs byte for byte", flush=True)
    lines = [line for line in transcript.splitlines() if line.startswith(("G7n spirv ", "G7n glsl "))]
    for line in lines:
        print(line, flush=True)

    sha = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()
    (OUT / "manifest.json").write_text(json.dumps({
        "clang": run(["clang-22", "--version"]), "lld": run(["ld.lld-22", "--version"]),
        "kumo_elf_sha256": sha(kumo_elf), "linux_elf_sha256": sha(linux_elf),
        "spirv_sha256": sha(ref / "kumo_paint_v10.spv"),
        "reference_sha256": {n: sha(ref / n) for n in ("kumo_paint_v10.h", "kumo_paint_v10.c")},
        "inputs_sha256": {str(p): sha(p) for p in sorted([
            TOOL / "compiler-smoke.c", TOOL / "compiler-smoke-glsl.cpp", TOOL / "build-compiler.py",
            TOOL / "g7n/paint.comp",
            TOOL / "g7n/math.comp", ROOT / "shaders/mali/kumo_paint.cl",
            SOURCE / "src/panfrost/clc/pan_compile.c"])},
        "kumo_flags": kumo_flags, "linux_flags": linux_flags,
        "expected_lines": lines,
    }, indent=2) + "\n")
    print(f"G7n compiler smoke built: {kumo_elf}", flush=True)


if __name__ == "__main__":
    main()
