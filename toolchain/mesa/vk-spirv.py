"""VK3-a/VK4: generate or verify the committed SPIR-V words of KUMO's Vulkan proof shaders.

Generation (needs glslangValidator and spirv-val). It is per shader, so a pinned artifact is
never regenerated by accident: VK3-a's compute header records glslang 15.1.0 and
SPIRV-Tools v2025.1 (K2). VK4's were generated in the offline Mesa container
(kumo-mesa-drivers-g7k: glslang 16.6.0, SPIRV-Tools v2026.4), whose repository mount is
read-only, hence --out:
  python3 toolchain/mesa/vk-spirv.py --glslang PATH --spirv-val PATH --shader vk-triangle.vert [--out DIR]
Verification (needs no tools: each header's words must hash to its recorded SHA-256, and its
recorded source hash must be the committed source's):
  python3 toolchain/mesa/vk-spirv.py --verify
"""
import argparse
import hashlib
import re
import struct
import subprocess
import tempfile
from pathlib import Path

TOOL = Path(__file__).resolve().parent
TARGET = "vulkan1.1"
# source -> (header, C array, slice)
SHADERS = {
    "vk-compute.comp": ("vk-compute.spv.h", "kumo_vk_compute_spv", "VK3-a"),
    "vk-triangle.vert": ("vk-triangle-vert.spv.h", "kumo_vk_triangle_vert_spv", "VK4"),
    "vk-triangle.frag": ("vk-triangle-frag.spv.h", "kumo_vk_triangle_frag_spv", "VK4"),
}


def words_of(header):
    text = header.read_text()
    body = re.search(r"\{(.*?)\};", text, re.S).group(1)
    words = [int(w, 16) for w in re.findall(r"0x[0-9a-f]{8}", body)]
    recorded = re.search(r"SPIR-V SHA-256 ([0-9a-f]{64})", text).group(1)
    return words, recorded


def verify_one(source, root=TOOL):
    header_name, array, slice_name = SHADERS[source]
    header = root / header_name
    words, recorded = words_of(header)
    data = struct.pack(f"<{len(words)}I", *words)
    assert words and words[0] == 0x07230203, f"{header.name}: not SPIR-V"
    actual = hashlib.sha256(data).hexdigest()
    assert actual == recorded, f"{header.name}: words hash to {actual}, header records {recorded}"
    source_hash = hashlib.sha256((TOOL / source).read_bytes()).hexdigest()
    assert source_hash in header.read_text(), f"{header.name} was not generated from this {source}"
    assert f"{array}[]" in header.read_text(), f"{header.name} does not define {array}"
    print(f"{slice_name} SPIR-V green: {len(words)} words, SHA-256 {actual}, from {source} {source_hash[:16]}")


def verify():
    for source in SHADERS:
        verify_one(source)


def generate(glslang, spirv_val, source, out):
    header_name, array, _ = SHADERS[source]
    with tempfile.TemporaryDirectory() as scratch:
        spv = Path(scratch) / (source + ".spv")
        subprocess.run([glslang, "-V", "--target-env", TARGET, "-o", spv, TOOL / source], check=True,
                       capture_output=True)
        subprocess.run([spirv_val, "--target-env", TARGET, spv], check=True)
        data = spv.read_bytes()
    version = subprocess.run([glslang, "--version"], check=True, capture_output=True,
                             text=True).stdout.splitlines()[0].strip()
    tools = subprocess.run([spirv_val, "--version"], check=True, capture_output=True,
                           text=True).stdout.splitlines()[0].split(" unknown")[0].strip()
    assert len(data) % 4 == 0
    words = struct.unpack(f"<{len(data) // 4}I", data)
    rows = [", ".join(f"0x{w:08x}" for w in words[i:i + 6]) for i in range(0, len(words), 6)]
    out.mkdir(parents=True, exist_ok=True)
    (out / header_name).write_text(
        "/* SPDX-License-Identifier: MIT */\n"
        f"/* Generated by vk-spirv.py from {source} (source SHA-256 "
        f"{hashlib.sha256((TOOL / source).read_bytes()).hexdigest()})\n"
        f" * with {version}, --target-env {TARGET}, and checked by spirv-val ({tools}). Do not edit.\n"
        f" * {len(words)} words, SPIR-V SHA-256 {hashlib.sha256(data).hexdigest()}. */\n"
        "#pragma once\n#include <stdint.h>\n\n"
        f"static const uint32_t {array}[] = {{\n    " + ",\n    ".join(rows) + ",\n};\n")
    verify_one(source, out)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--verify", action="store_true")
    parser.add_argument("--glslang", default="glslangValidator")
    parser.add_argument("--spirv-val", default="spirv-val")
    parser.add_argument("--shader", action="append", choices=sorted(SHADERS), default=[])
    parser.add_argument("--out", type=Path, default=TOOL)
    args = parser.parse_args()
    if args.verify:
        verify()
        return
    assert args.shader, "name each --shader to regenerate; pinned artifacts are never rewritten implicitly"
    for source in args.shader:
        generate(args.glslang, args.spirv_val, source, args.out)


if __name__ == "__main__":
    main()
