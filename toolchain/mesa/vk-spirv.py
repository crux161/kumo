"""VK3-a: generate or verify the committed SPIR-V words of vk-compute.comp.

Generation (needs glslangValidator and spirv-val; KUMO pins glslang 15.1.0 and
SPIRV-Tools v2025.1):
  python3 toolchain/mesa/vk-spirv.py --glslang PATH --spirv-val PATH
Verification (needs no tools: the header's words must hash to its recorded SHA-256):
  python3 toolchain/mesa/vk-spirv.py --verify
"""
import argparse
import hashlib
import re
import struct
import subprocess
import tempfile
from pathlib import Path

TOOL = Path(__file__).resolve().parent
SOURCE = TOOL / "vk-compute.comp"
HEADER = TOOL / "vk-compute.spv.h"
TARGET = "vulkan1.1"


def words_of(header):
    text = header.read_text()
    body = re.search(r"\{(.*?)\};", text, re.S).group(1)
    words = [int(w, 16) for w in re.findall(r"0x[0-9a-f]{8}", body)]
    recorded = re.search(r"SPIR-V SHA-256 ([0-9a-f]{64})", text).group(1)
    return words, recorded


def verify():
    words, recorded = words_of(HEADER)
    data = struct.pack(f"<{len(words)}I", *words)
    assert words and words[0] == 0x07230203, "not SPIR-V"
    actual = hashlib.sha256(data).hexdigest()
    assert actual == recorded, f"{HEADER.name}: words hash to {actual}, header records {recorded}"
    source = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    assert source in HEADER.read_text(), f"{HEADER.name} was not generated from this {SOURCE.name}"
    print(f"VK3-a SPIR-V green: {len(words)} words, SHA-256 {actual}, from {SOURCE.name} {source[:16]}")


def generate(glslang, spirv_val):
    with tempfile.TemporaryDirectory() as scratch:
        spv = Path(scratch) / "vk-compute.spv"
        subprocess.run([glslang, "-V", "--target-env", TARGET, "-o", spv, SOURCE], check=True,
                       capture_output=True)
        subprocess.run([spirv_val, "--target-env", TARGET, spv], check=True)
        data = spv.read_bytes()
    version = subprocess.run([glslang, "--version"], check=True, capture_output=True,
                             text=True).stdout.splitlines()[0].strip()
    assert len(data) % 4 == 0
    words = struct.unpack(f"<{len(data) // 4}I", data)
    rows = [", ".join(f"0x{w:08x}" for w in words[i:i + 6]) for i in range(0, len(words), 6)]
    HEADER.write_text(
        "/* SPDX-License-Identifier: MIT */\n"
        f"/* Generated by vk-spirv.py from {SOURCE.name} (source SHA-256 "
        f"{hashlib.sha256(SOURCE.read_bytes()).hexdigest()})\n"
        f" * with {version}, --target-env {TARGET}, and checked by spirv-val. Do not edit.\n"
        f" * {len(words)} words, SPIR-V SHA-256 {hashlib.sha256(data).hexdigest()}. */\n"
        "#pragma once\n#include <stdint.h>\n\n"
        "static const uint32_t kumo_vk_compute_spv[] = {\n    " + ",\n    ".join(rows) + ",\n};\n")
    verify()


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--verify", action="store_true")
    parser.add_argument("--glslang", default="glslangValidator")
    parser.add_argument("--spirv-val", default="spirv-val")
    args = parser.parse_args()
    if args.verify:
        verify()
    else:
        generate(args.glslang, args.spirv_val)


if __name__ == "__main__":
    main()
