/// The request/reply transport the server runs over. The real implementation will
/// wrap KUMO channels; tests use an in-memory fake.
pub trait Transport {
    fn recv(&mut self, buf: &mut [u8]) -> Option<usize>;
    fn send(&mut self, frame: &[u8]);
}

/// Server state for one tty session.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct TtyServer<const N: usize = DEFAULT_LINE_BYTES> {
    line: LineDiscipline<N>,
    /// The line typed while canonical with echo off. It is never copied into `submitted`.
    secret: SecretLine<N>,
    mode: TerminalMode,
    window_size: WindowSize,
    submitted: [u8; N],
    submitted_len: usize,
    submitted_ready: bool,
}

impl<const N: usize> TtyServer<N> {
    pub const fn new() -> TtyServer<N> {
        TtyServer {
            line: LineDiscipline::new(),
            secret: SecretLine::new(),
            mode: TerminalMode::cooked(),
            window_size: WindowSize::text_console(),
            submitted: [0; N],
            submitted_len: 0,
            submitted_ready: false,
        }
    }

    pub fn pending(&self) -> &[u8] {
        self.line.pending()
    }

    pub const fn mode(&self) -> TerminalMode {
        self.mode
    }

    pub const fn window_size(&self) -> WindowSize {
        self.window_size
    }

    /// Handle one request frame, writing a reply frame.
    pub fn dispatch(&mut self, request: &[u8], reply: &mut [u8]) -> usize {
        let Some(request) = Request::decode(request) else {
            return write_reply(reply, TTY_BAD_REQUEST, Echo::none(), None);
        };
        match request {
            Request::Clear => {
                self.line.clear();
                write_reply(reply, TTY_OK, Echo::none(), None)
            }
            Request::ForgetHistory => {
                self.line.forget_history();
                self.secret.wipe();
                write_reply(reply, TTY_OK, Echo::none(), None)
            }
            Request::Shutdown => 0,
            Request::Write(byte) => write_reply(reply, TTY_OK, Echo::byte(byte), None),
            Request::GetMode => write_mode_reply(reply, self.mode),
            Request::GetWindowSize => write_window_size_reply(reply, self.window_size),
            Request::SetWindowSize(size) => {
                if size.rows == 0 || size.columns == 0 {
                    return write_reply(reply, TTY_BAD_REQUEST, Echo::none(), None);
                }
                self.window_size = size;
                write_window_size_reply(reply, self.window_size)
            }
            Request::SetMode { mode, action } => {
                self.mode = mode;
                self.secret.wipe();
                if action == SetModeAction::Flush {
                    self.line.clear();
                    self.submitted_len = 0;
                    self.submitted_ready = false;
                }
                write_reply(reply, TTY_OK, Echo::none(), None)
            }
            Request::Read => {
                if self.submitted_ready {
                    let n = self.submitted_len;
                    self.submitted_ready = false;
                    self.submitted_len = 0;
                    write_reply(reply, TTY_OK, Echo::none(), Some(&self.submitted[..n]))
                } else {
                    write_reply(reply, TTY_OK, Echo::none(), None)
                }
            }
            Request::Input(byte) => {
                if !self.mode.canonical {
                    if self.submitted.is_empty() {
                        return write_reply(reply, TTY_OVERFLOW, Echo::none(), None);
                    }
                    self.submitted[0] = byte;
                    self.submitted_len = 1;
                    self.submitted_ready = true;
                    let echo = if self.mode.echo {
                        Echo::byte(byte)
                    } else {
                        Echo::none()
                    };
                    return write_reply(reply, TTY_OK, echo, Some(&self.submitted[..1]));
                }
                if !self.mode.echo {
                    // The line goes out in this reply only: `Read` never sees it and nothing
                    // keeps it.
                    let mut secret = [0u8; N];
                    let result = self.secret.feed_byte(byte, &mut secret);
                    let n = match result.event {
                        LineEvent::Submitted { len } => {
                            write_reply(reply, TTY_OK, result.echo, Some(&secret[..len]))
                        }
                        LineEvent::Overflow => write_reply(reply, TTY_OVERFLOW, result.echo, None),
                        LineEvent::None => write_reply(reply, TTY_OK, result.echo, None),
                    };
                    for byte in secret.iter_mut() {
                        // SAFETY: `byte` is a valid, exclusive reference.
                        unsafe { core::ptr::write_volatile(byte, 0) };
                    }
                    return n;
                }
                let mut submitted = [0u8; N];
                let result = self.line.feed_byte(byte, &mut submitted);
                let line = match result.event {
                    LineEvent::None => None,
                    LineEvent::Submitted { len } => {
                        self.submitted[..len].copy_from_slice(&submitted[..len]);
                        self.submitted_len = len;
                        self.submitted_ready = true;
                        Some(&submitted[..len])
                    }
                    LineEvent::Overflow => {
                        return write_reply(reply, TTY_OVERFLOW, result.echo, None);
                    }
                };
                write_reply(reply, TTY_OK, result.echo, line)
            }
        }
    }

    /// Handle exactly one transport request/reply exchange. Returns `false` when
    /// the transport closes before yielding a request.
    pub fn serve_once<T: Transport>(
        &mut self,
        transport: &mut T,
        request_buf: &mut [u8],
        reply_buf: &mut [u8],
    ) -> bool {
        let Some(n) = transport.recv(request_buf) else {
            return false;
        };
        if Request::decode(&request_buf[..n]) == Some(Request::Shutdown) {
            return false;
        }
        let reply_len = self.dispatch(&request_buf[..n], reply_buf);
        if reply_len != 0 {
            transport.send(&reply_buf[..reply_len]);
            // A reply can carry a password line; do not leave it in the buffer.
            for byte in reply_buf[..reply_len].iter_mut() {
                // SAFETY: `byte` is a valid, exclusive reference.
                unsafe { core::ptr::write_volatile(byte, 0) };
            }
        }
        true
    }
}

impl TtyServer<DEFAULT_LINE_BYTES> {
    /// Run request/reply exchanges until the transport closes.
    pub fn serve<T: Transport>(&mut self, transport: &mut T) {
        // Expose excess bytes instead of truncating an oversized message into
        // a valid window-size setter. — KESTREL
        let mut request_buf = [0u8; REQUEST_BUF_BYTES + 1];
        let mut reply_buf = [0u8; REPLY_BUF_BYTES];
        while self.serve_once(transport, &mut request_buf, &mut reply_buf) {}
    }
}

impl<const N: usize> Default for TtyServer<N> {
    fn default() -> Self {
        Self::new()
    }
}

fn write_reply(reply: &mut [u8], status: u8, echo: Echo, line: Option<&[u8]>) -> usize {
    let echo = echo.as_bytes();
    // An empty submitted line is still a line: Enter alone re-prompts the shell, and an empty
    // password is an attempt (J564). Only `None` is "no line yet".
    let event = if line.is_some() {
        EVENT_LINE
    } else {
        EVENT_NONE
    };
    let line = line.unwrap_or(&[]);
    let Some(total) = REPLY_HEADER_BYTES
        .checked_add(echo.len())
        .and_then(|n| n.checked_add(line.len()))
    else {
        return 0;
    };
    let Some(out) = reply.get_mut(..total) else {
        return 0;
    };
    if echo.len() > u16::MAX as usize || line.len() > u16::MAX as usize {
        return 0;
    }
    out[0] = status;
    out[1] = event;
    out[2..4].copy_from_slice(&(echo.len() as u16).to_le_bytes());
    out[4..6].copy_from_slice(&(line.len() as u16).to_le_bytes());
    out[REPLY_HEADER_BYTES..REPLY_HEADER_BYTES + echo.len()].copy_from_slice(echo);
    out[REPLY_HEADER_BYTES + echo.len()..total].copy_from_slice(line);
    total
}

fn write_mode_reply(reply: &mut [u8], mode: TerminalMode) -> usize {
    let Some(out) = reply.get_mut(..REPLY_HEADER_BYTES + 1) else {
        return 0;
    };
    out[0] = TTY_OK;
    out[1] = EVENT_MODE;
    out[2..4].copy_from_slice(&0u16.to_le_bytes());
    out[4..6].copy_from_slice(&1u16.to_le_bytes());
    out[REPLY_HEADER_BYTES] = mode.encode();
    REPLY_HEADER_BYTES + 1
}

fn write_window_size_reply(reply: &mut [u8], window_size: WindowSize) -> usize {
    let Some(out) = reply.get_mut(..REPLY_HEADER_BYTES + 4) else {
        return 0;
    };
    out[0] = TTY_OK;
    out[1] = EVENT_WINDOW_SIZE;
    out[2..4].copy_from_slice(&0u16.to_le_bytes());
    out[4..6].copy_from_slice(&4u16.to_le_bytes());
    out[REPLY_HEADER_BYTES..REPLY_HEADER_BYTES + 2]
        .copy_from_slice(&window_size.rows.to_le_bytes());
    out[REPLY_HEADER_BYTES + 2..REPLY_HEADER_BYTES + 4]
        .copy_from_slice(&window_size.columns.to_le_bytes());
    REPLY_HEADER_BYTES + 4
}

