//! `ttyd` - the P8 TTY line-discipline core.
//!
//! This crate is the host-testable center of the future userspace terminal server.
//! It owns no device and touches no framebuffer: drivers feed it input bytes over
//! IPC, and it returns the bytes that should be echoed plus completed command
//! lines for Kumoza/persona-posix clients.
//!
//! Recovery class: stateless / soft-state (`DESIGN/002`). The edit buffer is not
//! durable truth; on restart, clients reconnect and any half-typed line is lost.

#[cfg(test)]
extern crate alloc;

/// Default cooked-line capacity, matching the current Sora scaffold buffer.
pub const DEFAULT_LINE_BYTES: usize = 256;

/// One-byte request: clear the current edit line.
pub const OP_CLEAR: u8 = 0x00;
/// Two-byte request: feed one input byte (`[OP_INPUT, byte]`).
pub const OP_INPUT: u8 = 0x01;
/// Two-byte request: write one output byte (`[OP_WRITE, byte]`).
pub const OP_WRITE: u8 = 0x02;
/// One-byte request: read the last submitted line, if any.
pub const OP_READ: u8 = 0x03;
/// One-byte request: read the terminal's canonical/echo mode.
pub const OP_GET_MODE: u8 = 0x04;
/// Three-byte request: set mode and application timing (`[OP_SET_MODE, flags, action]`).
pub const OP_SET_MODE: u8 = 0x05;
/// One-byte request: read the terminal's dimensions in character cells.
pub const OP_GET_WINDOW_SIZE: u8 = 0x06;
/// Five-byte request: set the terminal's dimensions (`[OP_SET_WINDOW_SIZE, rows_le(2),
/// columns_le(2)]`). It is `TIOCSWINSZ`, sent by whoever owns the display the session draws on.
pub const OP_SET_WINDOW_SIZE: u8 = 0x07;
/// One-byte request: forget every remembered line, as a new login session starts (J564).
pub const OP_FORGET_HISTORY: u8 = 0x08;
/// One-byte request: terminate the serve loop without a reply.
pub const OP_SHUTDOWN: u8 = 0xff;

/// Reply status: request handled.
pub const TTY_OK: u8 = 0x00;
/// Reply status: malformed request frame.
pub const TTY_BAD_REQUEST: u8 = 0x01;
/// Reply status: the line or reply buffer was full.
pub const TTY_OVERFLOW: u8 = 0x02;

/// Reply event: no completed line in this reply.
pub const EVENT_NONE: u8 = 0x00;
/// Reply event: the reply carries one submitted line.
pub const EVENT_LINE: u8 = 0x01;
/// Reply event: the reply carries one encoded [`TerminalMode`].
pub const EVENT_MODE: u8 = 0x02;
/// Reply event: the reply carries one encoded [`WindowSize`].
pub const EVENT_WINDOW_SIZE: u8 = 0x03;

/// Request buffer size for the current protocol: the largest frame, `OP_SET_WINDOW_SIZE`'s.
pub const REQUEST_BUF_BYTES: usize = 5;
/// Reply header: status, event, echo_len_le, line_len_le.
pub const REPLY_HEADER_BYTES: usize = 6;
/// Largest echo generated by one cooked input byte. Middle-of-line edits can redraw the suffix and
/// move the cursor back. History redraws require backspacing the whole line, space-overwriting,
/// backspacing again, and echoing the new line. Thus 4x default line + 1 is safe.
pub const MAX_ECHO_BYTES: usize = DEFAULT_LINE_BYTES * 4 + 1;
/// Reply buffer size for a default-sized TTY session.
pub const REPLY_BUF_BYTES: usize = REPLY_HEADER_BYTES + MAX_ECHO_BYTES + DEFAULT_LINE_BYTES;

/// The maximum number of historical lines retained in the buffer.
pub const HISTORY_CAPACITY: usize = 8;

/// Known builtin command names for tab completion, sorted alphabetically.
pub const BUILTINS: &[&[u8]] = &[
    b"cat",
    b"echo",
    b"false",
    b"help",
    b"hostname",
    b"id",
    b"logout",
    b"ls",
    b"run",
    b"true",
    b"wc",
    b"whoami",
];

const ENTER_ECHO: &[u8] = b"\r\n";
const CTRL_C_ECHO: &[u8] = b"^C\r\n";
const BELL: &[u8] = b"\x07";
const ESC: u8 = 0x1b;
const BACKSPACE: u8 = 0x08;

/// The terminal semantics owned by `ttyd`, independent of any libc's `termios` layout.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct TerminalMode {
    pub canonical: bool,
    pub echo: bool,
}

impl TerminalMode {
    const CANONICAL: u8 = 1 << 0;
    const ECHO: u8 = 1 << 1;
    const KNOWN: u8 = Self::CANONICAL | Self::ECHO;

    pub const fn cooked() -> TerminalMode {
        TerminalMode {
            canonical: true,
            echo: true,
        }
    }

    pub const fn raw() -> TerminalMode {
        TerminalMode {
            canonical: false,
            echo: false,
        }
    }

    pub const fn encode(self) -> u8 {
        (if self.canonical { Self::CANONICAL } else { 0 })
            | (if self.echo { Self::ECHO } else { 0 })
    }

    pub const fn decode(flags: u8) -> Option<TerminalMode> {
        if flags & !Self::KNOWN != 0 {
            return None;
        }
        Some(TerminalMode {
            canonical: flags & Self::CANONICAL != 0,
            echo: flags & Self::ECHO != 0,
        })
    }
}

impl Default for TerminalMode {
    fn default() -> Self {
        Self::cooked()
    }
}

/// Terminal dimensions in character cells, independent of libc's `winsize` layout.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct WindowSize {
    pub rows: u16,
    pub columns: u16,
}

impl WindowSize {
    /// The size a session starts with: the classic text console. The display owner replaces
    /// it with [`Request::SetWindowSize`] once it knows its real grid (J557).
    pub const fn text_console() -> WindowSize {
        WindowSize {
            rows: 24,
            columns: 80,
        }
    }
}

impl Default for WindowSize {
    fn default() -> Self {
        Self::text_console()
    }
}

/// When a mode change becomes visible, matching POSIX's three `tcsetattr` actions.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum SetModeAction {
    Now,
    Drain,
    Flush,
}

impl SetModeAction {
    pub const fn encode(self) -> u8 {
        match self {
            SetModeAction::Now => 0,
            SetModeAction::Drain => 1,
            SetModeAction::Flush => 2,
        }
    }

    pub const fn decode(value: u8) -> Option<SetModeAction> {
        match value {
            0 => Some(SetModeAction::Now),
            1 => Some(SetModeAction::Drain),
            2 => Some(SetModeAction::Flush),
            _ => None,
        }
    }
}

/// A decoded ttyd request.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Request {
    /// Drop the current edit line.
    Clear,
    /// Feed one raw input byte.
    Input(u8),
    /// Write one byte to the terminal output stream.
    Write(u8),
    /// Read one submitted line.
    Read,
    /// Read the current line-discipline mode.
    GetMode,
    /// Change canonical/echo behaviour at the requested POSIX boundary.
    SetMode {
        mode: TerminalMode,
        action: SetModeAction,
    },
    /// Read the current terminal dimensions.
    GetWindowSize,
    /// Set the terminal dimensions; both must be non-zero.
    SetWindowSize(WindowSize),
    /// Forget the history and the current edit line: one session's lines must not be recalled
    /// in the next.
    ForgetHistory,
    /// Gracefully stop the server.
    Shutdown,
}

impl Request {
    pub const fn input(byte: u8) -> Request {
        Request::Input(byte)
    }

    pub const fn clear() -> Request {
        Request::Clear
    }

    pub const fn write(byte: u8) -> Request {
        Request::Write(byte)
    }

    pub const fn read() -> Request {
        Request::Read
    }

    pub const fn get_mode() -> Request {
        Request::GetMode
    }

    pub const fn set_mode(mode: TerminalMode, action: SetModeAction) -> Request {
        Request::SetMode { mode, action }
    }

    pub const fn get_window_size() -> Request {
        Request::GetWindowSize
    }

    pub const fn set_window_size(size: WindowSize) -> Request {
        Request::SetWindowSize(size)
    }

    pub const fn forget_history() -> Request {
        Request::ForgetHistory
    }

    pub const fn shutdown() -> Request {
        Request::Shutdown
    }

    pub fn encode_into(&self, out: &mut [u8]) -> Option<usize> {
        match *self {
            Request::Clear
            | Request::Read
            | Request::GetMode
            | Request::GetWindowSize
            | Request::ForgetHistory
            | Request::Shutdown => {
                let frame = out.get_mut(..1)?;
                frame[0] = match *self {
                    Request::Clear => OP_CLEAR,
                    Request::Read => OP_READ,
                    Request::GetMode => OP_GET_MODE,
                    Request::GetWindowSize => OP_GET_WINDOW_SIZE,
                    Request::ForgetHistory => OP_FORGET_HISTORY,
                    Request::Shutdown => OP_SHUTDOWN,
                    Request::Input(_)
                    | Request::Write(_)
                    | Request::SetMode { .. }
                    | Request::SetWindowSize(_) => unreachable!(),
                };
                Some(1)
            }
            Request::Input(byte) | Request::Write(byte) => {
                let frame = out.get_mut(..2)?;
                frame[0] = match *self {
                    Request::Input(_) => OP_INPUT,
                    Request::Write(_) => OP_WRITE,
                    Request::Clear
                    | Request::Read
                    | Request::GetMode
                    | Request::GetWindowSize
                    | Request::SetMode { .. }
                    | Request::SetWindowSize(_)
                    | Request::ForgetHistory
                    | Request::Shutdown => {
                        unreachable!()
                    }
                };
                frame[1] = byte;
                Some(2)
            }
            Request::SetMode { mode, action } => {
                let frame = out.get_mut(..3)?;
                frame[0] = OP_SET_MODE;
                frame[1] = mode.encode();
                frame[2] = action.encode();
                Some(3)
            }
            Request::SetWindowSize(size) => {
                let frame = out.get_mut(..5)?;
                frame[0] = OP_SET_WINDOW_SIZE;
                frame[1..3].copy_from_slice(&size.rows.to_le_bytes());
                frame[3..5].copy_from_slice(&size.columns.to_le_bytes());
                Some(5)
            }
        }
    }

    pub fn decode(raw: &[u8]) -> Option<Request> {
        match raw {
            [OP_CLEAR] => Some(Request::Clear),
            [OP_INPUT, byte] => Some(Request::Input(*byte)),
            [OP_WRITE, byte] => Some(Request::Write(*byte)),
            [OP_READ] => Some(Request::Read),
            [OP_GET_MODE] => Some(Request::GetMode),
            [OP_SET_MODE, flags, action] => Some(Request::SetMode {
                mode: TerminalMode::decode(*flags)?,
                action: SetModeAction::decode(*action)?,
            }),
            [OP_GET_WINDOW_SIZE] => Some(Request::GetWindowSize),
            [OP_SET_WINDOW_SIZE, r0, r1, c0, c1] => Some(Request::SetWindowSize(WindowSize {
                rows: u16::from_le_bytes([*r0, *r1]),
                columns: u16::from_le_bytes([*c0, *c1]),
            })),
            [OP_FORGET_HISTORY] => Some(Request::ForgetHistory),
            [OP_SHUTDOWN] => Some(Request::Shutdown),
            _ => None,
        }
    }
}

/// Parsed view of a ttyd reply frame.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Reply<'a> {
    pub status: u8,
    pub echo: &'a [u8],
    pub line: Option<&'a [u8]>,
    pub mode: Option<TerminalMode>,
    pub window_size: Option<WindowSize>,
}

impl<'a> Reply<'a> {
    pub fn parse(raw: &'a [u8]) -> Option<Reply<'a>> {
        let header = raw.get(..REPLY_HEADER_BYTES)?;
        let status = header[0];
        let event = header[1];
        let echo_len = u16::from_le_bytes([header[2], header[3]]) as usize;
        let line_len = u16::from_le_bytes([header[4], header[5]]) as usize;
        let echo_start = REPLY_HEADER_BYTES;
        let line_start = echo_start.checked_add(echo_len)?;
        let line_end = line_start.checked_add(line_len)?;
        let echo = raw.get(echo_start..line_start)?;
        let line_bytes = raw.get(line_start..line_end)?;
        let (line, mode, window_size) = match event {
            EVENT_NONE if line_len == 0 => (None, None, None),
            EVENT_LINE => (Some(line_bytes), None, None),
            EVENT_MODE if line_len == 1 => (None, Some(TerminalMode::decode(line_bytes[0])?), None),
            EVENT_WINDOW_SIZE if line_len == 4 => (
                None,
                None,
                Some(WindowSize {
                    rows: u16::from_le_bytes([line_bytes[0], line_bytes[1]]),
                    columns: u16::from_le_bytes([line_bytes[2], line_bytes[3]]),
                }),
            ),
            _ => return None,
        };
        Some(Reply {
            status,
            echo,
            line,
            mode,
            window_size,
        })
    }
}

/// Echo bytes emitted in response to one input byte.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Echo {
    bytes: [u8; MAX_ECHO_BYTES],
    len: u16,
}

impl Echo {
    pub const fn none() -> Echo {
        Echo {
            bytes: [0; MAX_ECHO_BYTES],
            len: 0,
        }
    }

    pub const fn byte(byte: u8) -> Echo {
        let mut bytes = [0; MAX_ECHO_BYTES];
        bytes[0] = byte;
        Echo { bytes, len: 1 }
    }

    pub fn bytes(bytes: &[u8]) -> Echo {
        let mut out = [0u8; MAX_ECHO_BYTES];
        let mut i = 0;
        while i < bytes.len() && i < out.len() {
            out[i] = bytes[i];
            i += 1;
        }
        Echo {
            bytes: out,
            len: i as u16,
        }
    }

    pub fn as_bytes(&self) -> &[u8] {
        &self.bytes[..self.len as usize]
    }

    pub const fn is_empty(&self) -> bool {
        self.len == 0
    }

    fn push(&mut self, byte: u8) {
        if (self.len as usize) < self.bytes.len() {
            self.bytes[self.len as usize] = byte;
            self.len += 1;
        }
    }

    fn push_bytes(&mut self, bytes: &[u8]) {
        for &byte in bytes {
            self.push(byte);
        }
    }

    fn push_repeat(&mut self, byte: u8, count: usize) {
        for _ in 0..count {
            self.push(byte);
        }
    }
}

/// Line-level event produced by one input byte.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum LineEvent {
    /// No completed line yet.
    None,
    /// A line was copied into the caller-provided output buffer.
    Submitted { len: usize },
    /// The input or output buffer was full, so the byte/line was not accepted.
    Overflow,
}

/// Result of feeding one byte through the line discipline.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct InputResult {
    pub echo: Echo,
    pub event: LineEvent,
}

impl InputResult {
    pub const fn none() -> InputResult {
        InputResult {
            echo: Echo::none(),
            event: LineEvent::None,
        }
    }
}

/// Canonical input with echo off: a password (PLAN/012). Bytes are kept, erased and submitted as
/// a cooked line's are, but nothing is echoed except the newline on Enter (POSIX `ECHONL`, as
/// `getpass` and `login` use it). Nothing is recorded in history or recalled from it, and Tab,
/// arrows and other escape sequences do nothing. Enter and Ctrl-C wipe the buffer; Ctrl-C rings
/// the bell so the typist knows the line is gone.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct SecretLine<const N: usize = DEFAULT_LINE_BYTES> {
    buf: [u8; N],
    len: usize,
    escape: EscapeState,
}

impl<const N: usize> SecretLine<N> {
    pub const fn new() -> SecretLine<N> {
        SecretLine {
            buf: [0; N],
            len: 0,
            escape: EscapeState::Ground,
        }
    }

    pub const fn len(&self) -> usize {
        self.len
    }

    pub const fn is_empty(&self) -> bool {
        self.len == 0
    }

    pub fn feed_byte(&mut self, byte: u8, submitted: &mut [u8]) -> InputResult {
        if self.escape != EscapeState::Ground {
            // Swallow the rest of an escape sequence: `ESC [` parameters, then a final byte.
            self.escape = match (self.escape, byte) {
                (EscapeState::Esc, b'[') => EscapeState::Csi,
                (EscapeState::Csi, 0x20..=0x3f) => EscapeState::Csi,
                _ => EscapeState::Ground,
            };
            return InputResult::none();
        }
        match byte {
            b'\r' | b'\n' => {
                let len = self.len;
                let Some(out) = submitted.get_mut(..len) else {
                    self.wipe();
                    return InputResult {
                        echo: Echo::bytes(ENTER_ECHO),
                        event: LineEvent::Overflow,
                    };
                };
                out.copy_from_slice(&self.buf[..len]);
                self.wipe();
                InputResult {
                    echo: Echo::bytes(ENTER_ECHO),
                    event: LineEvent::Submitted { len },
                }
            }
            0x03 => {
                self.wipe();
                InputResult {
                    echo: Echo::bytes(BELL),
                    event: LineEvent::None,
                }
            }
            ESC => {
                self.escape = EscapeState::Esc;
                InputResult::none()
            }
            0x08 | 0x7f => {
                if self.len > 0 {
                    self.len -= 1;
                    self.buf[self.len] = 0;
                }
                InputResult::none()
            }
            0x20..=0x7e if self.len < N => {
                self.buf[self.len] = byte;
                self.len += 1;
                InputResult::none()
            }
            0x20..=0x7e => InputResult {
                echo: Echo::bytes(BELL),
                event: LineEvent::None,
            },
            _ => InputResult::none(),
        }
    }

    /// Forget the line, overwriting it.
    pub fn wipe(&mut self) {
        for byte in self.buf.iter_mut() {
            // SAFETY: `byte` is a valid, exclusive reference.
            unsafe { core::ptr::write_volatile(byte, 0) };
        }
        self.len = 0;
        self.escape = EscapeState::Ground;
    }
}

impl<const N: usize> Default for SecretLine<N> {
    fn default() -> Self {
        Self::new()
    }
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum EscapeState {
    Ground,
    Esc,
    Csi,
    CsiParam { value: u16 },
}

/// Cooked line discipline for one TTY session.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct LineDiscipline<const N: usize = DEFAULT_LINE_BYTES> {
    buf: [u8; N],
    len: usize,
    cursor: usize,
    escape: EscapeState,
    history: [[u8; N]; HISTORY_CAPACITY],
    history_len: [usize; HISTORY_CAPACITY],
    history_count: usize,
    history_index: usize,
    saved_edit: [u8; N],
    saved_len: usize,
}

impl<const N: usize> LineDiscipline<N> {
    pub const fn new() -> LineDiscipline<N> {
        LineDiscipline {
            buf: [0; N],
            len: 0,
            cursor: 0,
            escape: EscapeState::Ground,
            history: [[0; N]; HISTORY_CAPACITY],
            history_len: [0; HISTORY_CAPACITY],
            history_count: 0,
            history_index: 0,
            saved_edit: [0; N],
            saved_len: 0,
        }
    }

    /// Bytes currently typed but not yet submitted.
    pub fn pending(&self) -> &[u8] {
        &self.buf[..self.len]
    }

    pub const fn cursor(&self) -> usize {
        self.cursor
    }

    /// Drop the current edit line.
    pub fn clear(&mut self) {
        self.len = 0;
        self.cursor = 0;
        self.escape = EscapeState::Ground;
        self.history_index = 0;
    }

    /// Forget every remembered line and the one being edited, overwriting them.
    pub fn forget_history(&mut self) {
        for byte in self
            .history
            .iter_mut()
            .flatten()
            .chain(self.buf.iter_mut())
            .chain(self.saved_edit.iter_mut())
        {
            // SAFETY: `byte` is a valid, exclusive reference.
            unsafe { core::ptr::write_volatile(byte, 0) };
        }
        self.history_len = [0; HISTORY_CAPACITY];
        self.history_count = 0;
        self.saved_len = 0;
        self.clear();
    }

    /// Feed one raw input byte.
    ///
    /// Printable ASCII is appended and echoed. Backspace/Delete erase one byte.
    /// Enter submits the current line into `submitted`, echoes CRLF, and resets the edit buffer.
    /// Ctrl-C cancels the current edit line with a visible marker. Other control bytes are ignored.
    pub fn feed_byte(&mut self, byte: u8, submitted: &mut [u8]) -> InputResult {
        if self.escape != EscapeState::Ground {
            return self.feed_escape(byte);
        }
        match byte {
            b'\r' | b'\n' => self.submit(submitted),
            0x03 => self.cancel(),
            ESC => {
                self.escape = EscapeState::Esc;
                InputResult::none()
            }
            0x09 => self.tab_complete(),
            0x08 | 0x7f => self.backspace(),
            0x20..=0x7e => self.printable(byte),
            _ => InputResult::none(),
        }
    }

    fn feed_escape(&mut self, byte: u8) -> InputResult {
        match self.escape {
            EscapeState::Ground => InputResult::none(),
            EscapeState::Esc => {
                if byte == b'[' {
                    self.escape = EscapeState::Csi;
                } else {
                    self.escape = EscapeState::Ground;
                }
                InputResult::none()
            }
            EscapeState::Csi => match byte {
                b'A' => self.finish_escape_with(Self::history_up),
                b'B' => self.finish_escape_with(Self::history_down),
                b'C' => self.finish_escape_with(Self::move_right),
                b'D' => self.finish_escape_with(Self::move_left),
                b'H' => self.finish_escape_with(Self::move_home),
                b'F' => self.finish_escape_with(Self::move_end),
                b'0'..=b'9' => {
                    self.escape = EscapeState::CsiParam {
                        value: (byte - b'0') as u16,
                    };
                    InputResult::none()
                }
                _ => {
                    self.escape = EscapeState::Ground;
                    InputResult::none()
                }
            },
            EscapeState::CsiParam { value } => match byte {
                b'0'..=b'9' => {
                    self.escape = EscapeState::CsiParam {
                        value: value
                            .saturating_mul(10)
                            .saturating_add((byte - b'0') as u16),
                    };
                    InputResult::none()
                }
                b'~' => self.finish_escape_param(value),
                _ => {
                    self.escape = EscapeState::Ground;
                    InputResult::none()
                }
            },
        }
    }

    fn finish_escape_with(&mut self, op: fn(&mut Self) -> InputResult) -> InputResult {
        self.escape = EscapeState::Ground;
        op(self)
    }

    fn finish_escape_param(&mut self, value: u16) -> InputResult {
        self.escape = EscapeState::Ground;
        match value {
            1 | 7 => self.move_home(),
            3 => self.delete_forward(),
            4 | 8 => self.move_end(),
            _ => InputResult::none(),
        }
    }

    fn printable(&mut self, byte: u8) -> InputResult {
        if self.len >= self.buf.len() {
            return InputResult {
                echo: Echo::bytes(BELL),
                event: LineEvent::Overflow,
            };
        }
        for index in (self.cursor..self.len).rev() {
            self.buf[index + 1] = self.buf[index];
        }
        self.buf[self.cursor] = byte;
        self.len += 1;
        self.cursor += 1;
        let suffix = &self.buf[self.cursor..self.len];
        let mut echo = Echo::byte(byte);
        echo.push_bytes(suffix);
        echo.push_repeat(BACKSPACE, suffix.len());
        InputResult {
            echo,
            event: LineEvent::None,
        }
    }

    fn backspace(&mut self) -> InputResult {
        if self.cursor == 0 {
            return InputResult::none();
        }
        let removed = self.cursor - 1;
        for index in removed..self.len - 1 {
            self.buf[index] = self.buf[index + 1];
        }
        self.len -= 1;
        self.cursor -= 1;
        let mut echo = Echo::none();
        echo.push(BACKSPACE);
        echo.push_bytes(&self.buf[self.cursor..self.len]);
        echo.push(b' ');
        echo.push_repeat(BACKSPACE, self.len - self.cursor + 1);
        InputResult {
            echo,
            event: LineEvent::None,
        }
    }

    fn delete_forward(&mut self) -> InputResult {
        if self.cursor >= self.len {
            return InputResult::none();
        }
        for index in self.cursor..self.len - 1 {
            self.buf[index] = self.buf[index + 1];
        }
        self.len -= 1;
        let mut echo = Echo::none();
        echo.push_bytes(&self.buf[self.cursor..self.len]);
        echo.push(b' ');
        echo.push_repeat(BACKSPACE, self.len - self.cursor + 1);
        InputResult {
            echo,
            event: LineEvent::None,
        }
    }

    fn move_left(&mut self) -> InputResult {
        if self.cursor == 0 {
            return InputResult::none();
        }
        self.cursor -= 1;
        InputResult {
            echo: Echo::byte(BACKSPACE),
            event: LineEvent::None,
        }
    }

    fn move_right(&mut self) -> InputResult {
        if self.cursor >= self.len {
            return InputResult::none();
        }
        let byte = self.buf[self.cursor];
        self.cursor += 1;
        InputResult {
            echo: Echo::byte(byte),
            event: LineEvent::None,
        }
    }

    fn move_home(&mut self) -> InputResult {
        let count = self.cursor;
        self.cursor = 0;
        let mut echo = Echo::none();
        echo.push_repeat(BACKSPACE, count);
        InputResult {
            echo,
            event: LineEvent::None,
        }
    }

    fn move_end(&mut self) -> InputResult {
        let mut echo = Echo::none();
        echo.push_bytes(&self.buf[self.cursor..self.len]);
        self.cursor = self.len;
        InputResult {
            echo,
            event: LineEvent::None,
        }
    }

    fn cancel(&mut self) -> InputResult {
        self.len = 0;
        self.cursor = 0;
        self.escape = EscapeState::Ground;
        self.history_index = 0;
        InputResult {
            echo: Echo::bytes(CTRL_C_ECHO),
            event: LineEvent::None,
        }
    }

    fn submit(&mut self, submitted: &mut [u8]) -> InputResult {
        if submitted.len() < self.len {
            return InputResult {
                echo: Echo::bytes(BELL),
                event: LineEvent::Overflow,
            };
        }
        let len = self.len;
        submitted[..len].copy_from_slice(&self.buf[..len]);

        if len > 0 {
            // Push to history
            let shift = if self.history_count < HISTORY_CAPACITY {
                self.history_count
            } else {
                HISTORY_CAPACITY - 1
            };
            for i in (0..shift).rev() {
                self.history[i + 1] = self.history[i];
                self.history_len[i + 1] = self.history_len[i];
            }
            self.history[0][..len].copy_from_slice(&self.buf[..len]);
            self.history_len[0] = len;
            if self.history_count < HISTORY_CAPACITY {
                self.history_count += 1;
            }
        }

        self.len = 0;
        self.cursor = 0;
        self.escape = EscapeState::Ground;
        self.history_index = 0;
        InputResult {
            echo: Echo::bytes(ENTER_ECHO),
            event: LineEvent::Submitted { len },
        }
    }

    fn replace_line(&mut self, new_buf: &[u8], new_len: usize) -> InputResult {
        let mut echo = Echo::none();

        // 1. Erase the current line by backspacing to start, overwriting with spaces, and backspacing again
        echo.push_repeat(BACKSPACE, self.cursor);
        echo.push_repeat(b' ', self.len);
        echo.push_repeat(BACKSPACE, self.len);

        // 2. Load the new line
        self.buf[..new_len].copy_from_slice(&new_buf[..new_len]);
        self.len = new_len;
        self.cursor = new_len;

        // 3. Draw the new line
        echo.push_bytes(&self.buf[..new_len]);

        InputResult {
            echo,
            event: LineEvent::None,
        }
    }

    fn history_up(&mut self) -> InputResult {
        if self.history_count == 0 || self.history_index >= self.history_count {
            return InputResult {
                echo: Echo::bytes(BELL),
                event: LineEvent::None,
            };
        }

        if self.history_index == 0 {
            // Save current typing buffer before replacing
            self.saved_len = self.len;
            self.saved_edit[..self.len].copy_from_slice(&self.buf[..self.len]);
        }

        let idx = self.history_index;
        self.history_index += 1;

        let new_len = self.history_len[idx];
        let mut new_buf = [0u8; N];
        new_buf[..new_len].copy_from_slice(&self.history[idx][..new_len]);

        self.replace_line(&new_buf, new_len)
    }

    fn history_down(&mut self) -> InputResult {
        if self.history_index == 0 {
            return InputResult {
                echo: Echo::bytes(BELL),
                event: LineEvent::None,
            };
        }

        self.history_index -= 1;

        if self.history_index == 0 {
            // Restore saved typing buffer
            let new_len = self.saved_len;
            let mut new_buf = [0u8; N];
            new_buf[..new_len].copy_from_slice(&self.saved_edit[..new_len]);
            self.replace_line(&new_buf, new_len)
        } else {
            let idx = self.history_index - 1;
            let new_len = self.history_len[idx];
            let mut new_buf = [0u8; N];
            new_buf[..new_len].copy_from_slice(&self.history[idx][..new_len]);
            self.replace_line(&new_buf, new_len)
        }
    }

    /// Tab-complete the current word against the known builtins.
    ///
    /// Completion triggers only when the cursor is at the end of the line and the
    /// entire pending text is a single partial word (the command-name position).
    /// A unique prefix match replaces the buffer with the full name plus a trailing
    /// space; zero or multiple matches ring the bell. — OSPREY 2026-06-29
    fn tab_complete(&mut self) -> InputResult {
        // Only complete when cursor is at the end of the line.
        if self.cursor != self.len {
            return InputResult {
                echo: Echo::bytes(BELL),
                event: LineEvent::None,
            };
        }

        // Only complete when the pending text is a bare word (no spaces = command
        // name position). An empty line is ambiguous (all builtins match).
        let prefix = &self.buf[..self.len];
        if prefix.is_empty() || prefix.iter().any(|&b| b == b' ') {
            return InputResult {
                echo: Echo::bytes(BELL),
                event: LineEvent::None,
            };
        }

        // Collect matching builtins.
        let mut match_count: usize = 0;
        let mut matched: &[u8] = b"";
        for &builtin in BUILTINS {
            if builtin.len() >= prefix.len() && &builtin[..prefix.len()] == prefix {
                match_count += 1;
                matched = builtin;
            }
        }

        if match_count != 1 {
            return InputResult {
                echo: Echo::bytes(BELL),
                event: LineEvent::None,
            };
        }

        // Unique match — complete with the full name and a trailing space.
        let suffix_start = self.len;
        let new_len = matched.len() + 1; // name + space
        if new_len > self.buf.len() {
            return InputResult {
                echo: Echo::bytes(BELL),
                event: LineEvent::None,
            };
        }

        self.buf[..matched.len()].copy_from_slice(matched);
        self.buf[matched.len()] = b' ';
        self.len = new_len;
        self.cursor = new_len;

        let mut echo = Echo::none();
        echo.push_bytes(&self.buf[suffix_start..new_len]);
        InputResult {
            echo,
            event: LineEvent::None,
        }
    }
}

